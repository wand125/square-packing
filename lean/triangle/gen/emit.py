#!/usr/bin/env python3
"""Write a generated tree (JSON from tree.py) as a Lean data file checked by `decide +kernel`."""
import argparse
import json
from pathlib import Path

from q3 import Q3

ADM = {(-1, -1): 0, (-1, 1): 1, (1, -1): 2, (1, 1): 3}
BOX = {'x0': 0, 'x1': 1, 'y0': 2, 'y1': 3}
PAST_END = 1000


def rat(x):
    x = str(x)
    return f'({x} : ℚ)' if '/' in x or x.startswith('-') else x


def q3(s):
    v = s if isinstance(s, Q3) else Q3.parse(s)
    return f'q {rat(v.a)} {rat(v.b)}'


def upoly(ps):
    return '[' + ', '.join(q3(c) for c in ps) + ']'


def aff(f):
    return f'⟨{upoly(f["1"])}, {upoly(f["x"])}, {upoly(f["y"])}⟩'


def form_index(tag):
    if tag[0] == 'adm':
        return 4 * tag[1] + ADM[(tag[2], tag[3])]
    if tag[0] == 'box':
        return 12 + BOX[tag[1]]
    if tag[0] == 'lin':
        return 16 + tag[1]
    if tag[0] == 'mu':
        return PAST_END
    raise ValueError(tag)


def cert(es):
    return '[' + ', '.join(f'⟨{form_index(t)}, {d}, {i}, {q3(c)}⟩' for t, d, i, c in es) + ']'


def tree(n, out, ind=''):
    if 'leaf' in n:
        if n['leaf'] == 'empty':
            out.append(f'{ind}.empty {cert(n["cert"])}')
        elif n['leaf'] == 'cover':
            items = []
            for i in n['points']:
                cs = n['certs'][str(i)] if str(i) in n['certs'] else n['certs'][i]
                items.append(f'({i}, [' + ', '.join(cert(c) for c in cs) + '])')
            out.append(f'{ind}.cover [' + ', '.join(items) + ']')
        else:
            raise SystemExit('tree has a failed leaf')
        return
    s = n['split']
    if s == 'lin':
        out.append(f'{ind}.lin {aff(n["form"])}')
        tree(n['pos'], out, ind + '  ')
        tree(n['neg'], out, ind + '  ')
        return
    out.append(f'{ind}.s{s} ({q3(n["at"])})')
    tree(n['lo'], out, ind + '  ')
    tree(n['hi'], out, ind + '  ')


def paren(lines):
    # each child of a constructor must be parenthesised: rebuild with explicit parens
    return lines


def emit_tree(n):
    """A single Lean term (parenthesised)."""
    if 'leaf' in n:
        out = []
        tree(n, out)
        return '(' + out[0].strip() + ')'
    s = n['split']
    if s == 'lin':
        return f'(.lin {aff(n["form"])} {emit_tree(n["pos"])} {emit_tree(n["neg"])})'
    return f'(.s{s} ({q3(n["at"])}) {emit_tree(n["lo"])} {emit_tree(n["hi"])})'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('tree_json')
    ap.add_argument('cert_json')
    ap.add_argument('name')
    ap.add_argument('out')
    a = ap.parse_args()
    d = json.loads(Path(a.tree_json).read_text())
    c = json.loads(Path(a.cert_json).read_text())
    L = Q3.parse(c['L'])
    ytop = L * Q3(0, 1) * Q3(1) / 2
    pts = ', '.join(f'({q3(p["x"])}, {q3(p["y"])}, {rat(p["w"])})' for p in c['points'])
    lines = [
        'import Sqtri.Check',
        '',
        f'/-! Generated by `gen/emit.py` from `{Path(a.cert_json).name}`; checked by the kernel. -/',
        '',
        f'namespace SquarePacking.Tri.{a.name}',
        '',
        'open Tree',
        '',
        f'def L : Q3 := {q3(L)}',
        f'def yTop : Q3 := {q3(ytop)}',
        f'def pts : List Pt := [{pts}]',
        '',
        'theorem weights : weightsOk pts = true := by decide +kernel',
        '',
    ]
    for k, r in enumerate(d['roots']):
        U0, U1 = r['u']
        lines += [f'def tree{k} : Tree := {emit_tree(r["tree"])}', '',
                  f'theorem check{k} : check L pts Q3.zero L Q3.zero yTop ({q3(U0)}) ({q3(U1)}) [] tree{k} = true := by',
                  '  decide +kernel', '']
    lines.append(f'end SquarePacking.Tri.{a.name}')
    Path(a.out).write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
