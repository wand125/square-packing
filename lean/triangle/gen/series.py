#!/usr/bin/env python3
"""Lean file for the series n = T_(m-1) + 1 in a triangle of side m + 2/sqrt3: the upper-bound
packing (rows of axis-parallel squares) and the main theorem."""
import math
import sys
from pathlib import Path

m = int(sys.argv[1]); name = sys.argv[2]; out = Path(sys.argv[3])
r3 = math.sqrt(3)
sqs = []
k = 0
while True:
    cnt = math.floor(m - 2 * k / r3 + 1e-12)
    if cnt <= 0:
        break
    for j in range(cnt):
        # centre ((k+1)/sqrt3 + 1/2 + j, k + 1/2) = (1/2 + j) + (k+1)/3 * sqrt3
        sqs.append(f'⟨q ({2 * j + 1}/2) ({k + 1}/3), q ({2 * k + 1}/2) 0, q 1 0, q 0 0⟩')
    k += 1
n = len(sqs)
assert n == m * (m - 1) // 2 + 1, (m, n)
lines = [f'import Sqtri.Main', f'import Sqtri.Data.{name}.All', '',
         '/-! Generated by `gen/series.py`. -/', '', 'namespace SquarePacking.Tri', '',
         f'def sq_{name} : Fin {n} → Sq := ![' + ',\n  '.join(sqs) + ']', '',
         f'theorem minSideTri_{n} : minSideTri {n} = {m} + 2 / Real.sqrt 3 := by',
         f'  have hL : {name}.L.val = {m} + 2 / Real.sqrt 3 := by',
         f'    rw [two_div_sqrt3]; simp [{name}.L]',
         '  rw [← hL]',
         '  apply minSideTri_eq',
         f'  · exact packs_of_axisPackB {n} {name}.L sq_{name} (by decide +kernel)',
         f'  · exact le_of_checks {n} {name}.L {name}.yTop {name}.pts (yTop_val (by decide +kernel)) {name}.weights',
         f'      (by decide +kernel) {name}.tree0 {name}.tree1 {name}.tree2 {name}.check0 {name}.check1 {name}.check2',
         '', 'end SquarePacking.Tri', '']
out.write_text('\n'.join(lines))
print(n, 'squares')
